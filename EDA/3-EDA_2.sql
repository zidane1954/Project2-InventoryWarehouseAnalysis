-- 2. Berapa kuantitas reorder yang direkomendasikan ?
-- BISA DI ANALISIS DARI PERTANYAAN PERTAMA, REORDER LEVEL TIAP PRODUCT DAPAT DISESUAIKAN UNTUK SETIAP GUDANG KEMBALI, BERGANTUNG PADA MANAGER GUDANG DAN BERDASARKAN DENGAN DEMAND DARI BARANG DI TIAP TIAP GUDANG. 
-- SELAIN ITU BARANG YANG OVER STOCK DI GUDANG DAPAT DILAKUKAN TRANSFER STOCK KE YANG STATUS NYA KRITIS DAN WASPADA UNTUK MENGURANGI KERUGIAN. UNTUK BARANG YANG OVERSTOCK DI KEBANYAKAN GUDANG , DAPAT DIALKUKAN PROMO MARKETING GUNA MEMPUSH NYA UNTUK MEMINIMALISIR KERUGIN  
-- REORCER LEVEL BISA DI SESUAIKAN LAGI DNEGAN MENGHITUNG (DEMAND HARIAN X 3) X LEADTIMEDAYS , (BIAR SAAT BELI ADA SPARETIME AMAN) CUKUP . ` 
-- REORDER LEVEL DI ITUNG DARI DEMAND HARIAN X LEAD TIME + SAFETY STOCK UNTUK  DEMAND tertinggi + 3 BULAN
WITH SAFETY_STOCK AS (
SELECT PRODUCT_ID, MAX(DEMAND_HARIAN) AS MAXIMUM_DEMAND, AVG(DEMAND_HARIAN) AS RATA_DEMAND, MAX(LEAD_TIME_DAYS) AS MAXIMUM_LEAD, AVG(LEAD_TIME_DAYS) AS RATA_LEAD
FROM KLASIFIKASI_STOCK
GROUP BY PRODUCT_ID
) 
SELECT  K.WAREHOUSE_ID, K.CATEGORY, K.PRODUCT_ID, K.REORDER_LEVEL,ROUND((K.DEMAND_HARIAN * K.LEAD_TIME_DAYS) + (S.MAXIMUM_DEMAND + 90)) AS NEW_REORDER_LEVEL
FROM klasifikasi_stock K
LEFT JOIN SAFETY_STOCK S
	ON K.PRODUCT_ID = S.PRODUCT_ID
; 
