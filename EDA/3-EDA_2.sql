-- 1. Produk mana yang beresiko stockout dan berapa hari stoknya cukup ? 
-- PERHITUNGAN TOTAL STOCK SAAT INI
WITH ITUNGAN_STOCK AS (
SELECT 
    *, 
    ROW_NUMBER () OVER(PARTITION BY WAREHOUSE_ID, PRODUCT_ID ORDER BY MOVEMENT_ID DESC, movement_date DESC) AS URUTAN_PERGERAKAN
FROM
    stock_movements
), 
CURRENT_STOK AS (
SELECT MOVEMENT_ID, MOVEMENT_DATE, WAREHOUSE_ID, PRODUCT_ID, STOCK_AFTER_MOVEMENT AS STOK_SEKARANG 
FROM ITUNGAN_STOCK
WHERE URUTAN_PERGERAKAN = 1
), 
DEMAND AS (
SELECT WAREHOUSE_ID, PRODUCT_ID, SUM(QUANTITY_SOLD) AS DEMAND_TOTAL
FROM SALES_ORDERS
WHERE SO_STATUS NOT LIKE 'CANCELLED%'
GROUP BY WAREHOUSE_ID, PRODUCT_ID
ORDER BY WAREHOUSE_ID, PRODUCT_ID
) , 
TABEL_SISA_STOK AS (
SELECT 
	CS.WAREHOUSE_ID, 
	P.CATEGORY, 
	CS.PRODUCT_ID, 
	CS.STOK_SEKARANG, 
	coalesce(D.DEMAND_TOTAL,0) AS DEMAND_TOTAL,  
    ROUND(coalesce(D.DEMAND_TOTAL,0)/365, 3) AS DEMAND_HARIAN,
    ROUND(STOK_SEKARANG / NULLIF(COALESCE(D.DEMAND_TOTAL,0) / 365, 0), 2) AS HARI_KE_COVER, 
	P.UNIT_COST, 
	P.REORDER_LEVEL, 
	S.LEAD_TIME_DAYS
FROM CURRENT_STOK CS
LEFT JOIN demand d
	ON d.product_id = cs.product_id AND d.warehouse_id = cs.warehouse_id
RIGHT JOIN PRODUCTS P
	ON CS.PRODUCT_ID = P.PRODUCT_ID
JOIN SUPPLIERS S
	ON P.SUPPLIER_ID = S.SUPPLIER_ID
)
SELECT * , 
	CASE
        WHEN HARI_KE_COVER IS NULL AND STOK_SEKARANG = 0   THEN 'Tidak Aktif'
        WHEN HARI_KE_COVER IS NULL                         THEN 'Overstock'
        WHEN STOK_SEKARANG = 0  AND DEMAND_TOTAL > 0       THEN 'Stockout'
        WHEN HARI_KE_COVER < LEAD_TIME_DAYS                THEN 'Kritis'
        WHEN STOK_SEKARANG <= REORDER_LEVEL                THEN 'Waspada'
        ELSE 'Aman'
	END AS `STATUS`
FROM TABEL_SISA_STOK
;

