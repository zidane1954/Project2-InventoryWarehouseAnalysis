-- PENGADAAN DAN SUPPLIER
-- 1. SUPPLIER MANA YANG PUNYA LEAD TIME TERPANJANG DAN PRODUCT APA YANG TERDAMPAK
SELECT S.supplier_id, S.supplier_type, P.product_id, P.category, S.lead_time_days
FROM suppliers S 
JOIN products P 
	ON S.supplier_id = P.supplier_id 
WHERE S.lead_time_days > 25
ORDER BY S.lead_time_days DESC, supplier_id 
; 
-- 2. BERAPA PORSI ANGGARAN PENGADAAN SUPLIER LOKAL VS SUPLIER IMPOR
SELECT S.SUPPLIER_TYPE ,SUM(PO.PO_AMOUNT) AS TOTAL_PENGADAAN, ROUND(
        (SUM(PO.PO_AMOUNT) / (SELECT SUM(PO_AMOUNT) FROM purchase_orders WHERE po_status NOT LIKE '%CANCELLED%')) * 100, 
    2) AS PERSENTASE
FROM SUPPLIERS S
JOIN PRODUCTS P
	ON S.SUPPLIER_ID = P.SUPPLIER_ID 
LEFT JOIN purchase_orders PO
	ON  S.SUPPLIER_ID = PO.SUPPLIER_ID  AND P.PRODUCT_ID = PO.product_id
WHERE PO.po_status NOT LIKE 'CANCELLED'
GROUP BY S.SUPPLIER_TYPE
;

-- 3. SIAPA SUPPPLIER YANG MENYERAP ANGGARAN TERBESAR DAN SEBERAPA TERKONSENTRASI
SELECT S.SUPPLIER_ID ,S.SUPPLIER_TYPE, SUM(PO.PO_AMOUNT) AS TOTAL_PENGADAAN, ROUND(
        (SUM(PO.PO_AMOUNT) / (SELECT SUM(PO_AMOUNT) FROM purchase_orders WHERE po_status NOT LIKE '%CANCELLED%')) * 100, 
    2) AS PERSENTASE, S.lead_time_days
FROM SUPPLIERS S
JOIN PRODUCTS P
	ON S.SUPPLIER_ID = P.SUPPLIER_ID 
LEFT JOIN purchase_orders PO
	ON  S.SUPPLIER_ID = PO.SUPPLIER_ID  AND P.PRODUCT_ID = PO.product_id
WHERE PO.po_status NOT LIKE '%CANCELLED%'
GROUP BY S.SUPPLIER_ID,S.SUPPLIER_TYPE
ORDER BY SUM(PO.PO_AMOUNT) DESC
;




-- GUDANG DAN PERMINTAAN
-- 1. GUDANG MANA YANG PALING AKTIF DAN BERAPA TOTAL ASET NYA DARI TIAP GUDANG
-- BUAT TEMPORARY TABLE
CREATE TEMPORARY TABLE ANALISIS_GUDANG AS 
WITH ITUNGAN_STOCK AS (
SELECT 
    *, 
    ROW_NUMBER () OVER(PARTITION BY WAREHOUSE_ID, PRODUCT_ID ORDER BY MOVEMENT_ID DESC, movement_date DESC) AS URUTAN_PERGERAKAN
FROM
    stock_movements
), 
CURRENT_STOK AS (
SELECT MOVEMENT_ID, MOVEMENT_DATE, WAREHOUSE_ID, PRODUCT_ID, STOCK_AFTER_MOVEMENT AS STOK_SEKARANG 
FROM ITUNGAN_STOCK
WHERE URUTAN_PERGERAKAN = 1
)
SELECT 
	SM.warehouse_id, 
    W.CITY,
	SM.product_id, 
    COUNT(CASE WHEN SM.movement_type LIKE '%IN%' THEN 1 END) AS FREQ_MASUK, 
    SUM(CASE WHEN SM.movement_type LIKE '%IN%' THEN quantity ELSE 0 END) AS QTY_MASUK,
    COUNT(CASE WHEN SM.movement_type LIKE '%OUT%' THEN 1 END) AS FREQ_KELUAR, 
    SUM(CASE WHEN SM.movement_type LIKE '%OUT%' THEN quantity ELSE 0 END) AS QTY_KELUAR,
    CS.STOK_SEKARANG,
    P.UNIT_COST, 
    CS.STOK_SEKARANG * P.UNIT_COST AS ASET,
    W.CAPACITY_SQM
FROM stock_movements SM
JOIN CURRENT_STOK CS
	ON SM.product_id = CS.product_id AND SM.warehouse_id = CS.warehouse_id
JOIN PRODUCTS P 
	ON SM.product_id = P.product_id
LEFT JOIN warehouses W 
	ON SM.warehouse_id = W.warehouse_id
group by SM.warehouse_id, W.CITY, SM.product_id, CS.STOK_SEKARANG, W.CAPACITY_SQM
order by SM.warehouse_id, W.CITY, SM.product_id, CS.STOK_SEKARANG, W.CAPACITY_SQM
; 

SELECT 
	warehouse_id,
    city, 
    CAPACITY_SQM, 
    SUM(FREQ_MASUK) AS TOTAL_FREQ_MASUK,
    SUM(QTY_MASUK) AS TOTAL_QTY_MASUK,
    SUM(FREQ_KELUAR) AS TOTAL_FREQ_KELUAR,
    SUM(QTY_KELUAR) AS TOTAL_QTY_KELUAR,
    SUM(FREQ_MASUK) + SUM(FREQ_KELUAR) AS TOTAL_TRANSAKSI, 
    ROUND((SUM(FREQ_MASUK) + SUM(FREQ_KELUAR))/ CAPACITY_SQM, 2) AS TRANSAKSI_PER_METER,
    SUM(STOK_SEKARANG) AS TOTAL_STOCK, 
    SUM(ASET) AS TOTAL_ASET,
    ROUND(SUM(ASET)/ CAPACITY_SQM, 2) AS ASET_PER_METER
FROM ANALISIS_GUDANG
GROUP BY 
	warehouse_id,
    city , 
     CAPACITY_SQM
;

-- 2. TREN PESANAN PERDAERAH DAN PERBULAN

WITH T AS (
    SELECT DATE_FORMAT(s.so_date, '%Y-%m') 	AS bulan,
           w.city,
           COUNT(*)           				AS jml_so,
           SUM(s.quantity_sold)				AS qty_terjual
    FROM sales_orders s
    JOIN warehouses w ON w.warehouse_id = s.warehouse_id
    WHERE s.so_status not like  '%Cancelled%'
    GROUP BY DATE_FORMAT(s.so_date, '%Y-%m'), w.city
),
G AS (
    SELECT city, COUNT(*) AS jml_gudang 
    FROM warehouses 
    GROUP BY city
)
SELECT
    t.bulan, t.city, t.jml_so, t.qty_terjual,
    ROUND(t.jml_so / g.jml_gudang, 1)                    AS so_per_gudang,   
    ROUND(AVG(t.jml_so) OVER (PARTITION BY t.city ORDER BY t.bulan
                              ROWS BETWEEN 2 PRECEDING AND CURRENT ROW), 1) AS moving_avg_3bln,
    t.jml_so - LAG(t.jml_so) OVER (PARTITION BY t.city ORDER BY t.bulan)    AS selisih_dari_bulan_lalu
FROM T t
JOIN G g ON g.city = t.city
ORDER BY t.city, t.bulan;


