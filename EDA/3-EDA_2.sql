WITH STATUS_PEMBELIAN AS (
SELECT 
	WAREHOUSE_ID , PRODUCT_ID, 
	COUNT(CASE WHEN SO_STATUS LIKE 'Backorder%' THEN 1  END) AS JUMLAH_BACKORDER, 
    COUNT(CASE 	WHEN SO_STATUS LIKE 'Fulfilled%' THEN 1 END) AS JUMLAH_PESANAN_BERHASIL
FROM 
	SALES_ORDERS 
GROUP BY 
	WAREHOUSE_ID, PRODUCT_ID
ORDER BY 
	WAREHOUSE_ID, PRODUCT_ID
    
)

SELECT SP.WAREHOUSE_ID ,SP.PRODUCT_ID, SP.JUMLAH_BACKORDER, SP.JUMLAH_PESANAN_BERHASIL,  
ROUND((JUMLAH_BACKORDER / (JUMLAH_BACKORDER + JUMLAH_PESANAN_BERHASIL))*100, 2) AS PERSENAN_BACKORDER_RATE, K.`STATUS`
FROM STATUS_PEMBELIAN SP 
JOIN klasifikasi_stock K 
	ON K.PRODUCT_ID = SP.PRODUCT_ID AND K.WAREHOUSE_ID = SP.WAREHOUSE_ID
    WHERE JUMLAH_BACKORDER > 0
order by ROUND((JUMLAH_BACKORDER / (JUMLAH_BACKORDER + JUMLAH_PESANAN_BERHASIL))*100, 2) DESC
-- BACKORDER GACUMAN TERJADI KETIKA BARANG STOCKOUT.
; 


